function switchLanguage(lang) {
  // Simpan preferensi
  try { localStorage.setItem('polmind_lang', lang); } catch(e) {}

  applyTextTranslations(lang);
  applyImageTranslations(lang);
}

// Inisialisasi saat halaman siap
(function initLang() {
  const select = document.getElementById('languageSwitcher');
  const saved = (() => { try { return localStorage.getItem('polmind_lang'); } catch(e) { return null; } })();
  const htmlLang = (document.documentElement.getAttribute('lang') || 'id').toLowerCase();
  const startLang = (saved === 'en' || saved === 'id') ? saved : (htmlLang === 'en' ? 'en' : 'id');

  if (select) select.value = startLang;
  switchLanguage(startLang);

  // Listener dropdown
  if (select) {
    select.addEventListener('change', function() {
      switchLanguage(this.value);
    });
  }
})();

